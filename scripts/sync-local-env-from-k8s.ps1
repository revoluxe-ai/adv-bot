param(
    [string]$OutFile = (Join-Path (Split-Path -Parent $PSScriptRoot) ".env.k8s-sync"),
    [string]$NamespaceAdvBot = "prod-adv-bot",
    [string]$NamespaceAnalytics = "prod-analytics"
)

$ErrorActionPreference = "Stop"

$repoRoot = Split-Path -Parent $PSScriptRoot
$defaultKubeconfig = Join-Path $repoRoot "k8s\new-cluster\new-cluster-config.yaml"
if ($env:DEV_TUNNELS_KUBECONFIG) {
    $kubeconfig = $env:DEV_TUNNELS_KUBECONFIG
} elseif (Test-Path $defaultKubeconfig) {
    $kubeconfig = $defaultKubeconfig
} else {
    $kubeconfig = ""
}

if ($kubeconfig) {
    $env:KUBECONFIG = $kubeconfig
    Write-Host "KUBECONFIG=$kubeconfig"
}

function Get-K8sSecretPlainText {
    param(
        [string]$Namespace,
        [string]$SecretName,
        [string]$Key
    )
    $b64 = kubectl get secret $SecretName -n $Namespace -o "jsonpath={.data.$Key}" 2>$null
    if (-not $b64) {
        throw "Secret $Namespace/$SecretName key '$Key' not found"
    }
    return [System.Text.Encoding]::UTF8.GetString([System.Convert]::FromBase64String($b64))
}

function Get-K8sConfigMapValue {
    param(
        [string]$Namespace,
        [string]$ConfigMapName,
        [string]$Key
    )
    $value = kubectl get configmap $ConfigMapName -n $Namespace -o "jsonpath={.data.$Key}" 2>$null
    if (-not $value) {
        throw "ConfigMap $Namespace/$ConfigMapName key '$Key' not found"
    }
    return $value
}

function Get-WorkerExternalIp {
    $json = kubectl get nodes -o json 2>$null
    if (-not $json) {
        return "<NO_NODE_IP>"
    }
    $nodes = ($json | ConvertFrom-Json).items
    foreach ($node in $nodes) {
        $ip = $node.status.addresses | Where-Object { $_.type -eq "ExternalIP" } | Select-Object -ExpandProperty address -First 1
        if ($ip) { return $ip }
    }
    return ($nodes[0].status.addresses | Where-Object { $_.type -eq "InternalIP" } | Select-Object -ExpandProperty address -First 1)
}

function Get-ServiceNodePort {
    param(
        [string]$Namespace,
        [string]$ServiceName,
        [string]$PortName
    )
    $json = kubectl get svc $ServiceName -n $Namespace -o json 2>$null
    if (-not $json) {
        throw "Service not found: $Namespace/$ServiceName"
    }
    $svc = $json | ConvertFrom-Json
    foreach ($port in $svc.spec.ports) {
        if ($port.name -eq $PortName -and $port.nodePort) {
            return [int]$port.nodePort
        }
    }
    throw "NodePort not found on $Namespace/$ServiceName port=$PortName"
}

